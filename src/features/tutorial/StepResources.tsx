/**
 * StepResources.tsx
 * -----------------
 * Tutorial Step 2 — "Understand Your Resources"
 *
 * Interactive display of the four life-support resources. The player can click
 * each resource to see what happens when it drops, and drag a simulated slider
 * to watch resource bars change. Uses real starting values from missionDefaults.
 */

import { useState } from 'react';
import type { ReactElement } from 'react';
import { Zap, Droplets, Apple, Wind } from 'lucide-react';
import type { LucideIcon } from 'lucide-react';
import { STANDARD_RESOURCES, CONSTRAINED_RESOURCES } from '../mission/missionDefaults';

interface ResourceInfo {
  key: string;
  label: string;
  icon: LucideIcon;
  color: string;
  barColor: string;
  standard: number;
  constrained: number;
  description: string;
  warning: string;
  critical: string;
}

const RESOURCES: ResourceInfo[] = [
  {
    key: 'power',
    label: 'Power',
    icon: Zap,
    color: 'text-yellow-400',
    barColor: 'bg-yellow-400',
    standard: STANDARD_RESOURCES.power,
    constrained: CONSTRAINED_RESOURCES.power,
    description:
      'Generated by solar panels and RTGs. Powers life support, communications, and research equipment. Without power, everything shuts down.',
    warning: 'Below 35%: power rationing begins, slowing all systems.',
    critical: 'Below 15%: emergency shutdown. Life support fails within days.',
  },
  {
    key: 'water',
    label: 'Water',
    icon: Droplets,
    color: 'text-accent-blue',
    barColor: 'bg-accent-blue',
    standard: STANDARD_RESOURCES.water,
    constrained: CONSTRAINED_RESOURCES.water,
    description:
      'Recycled through life support and extracted from Martian ice. Essential for drinking, crop irrigation, and oxygen production.',
    warning: 'Below 35%: rationing reduces morale and crop output.',
    critical: 'Below 15%: dehydration risk. Health drops rapidly.',
  },
  {
    key: 'food',
    label: 'Food',
    icon: Apple,
    color: 'text-status-ok',
    barColor: 'bg-status-ok',
    standard: STANDARD_RESOURCES.food,
    constrained: CONSTRAINED_RESOURCES.food,
    description:
      'Grown in the greenhouse and supplemented by stored rations. The greenhouse needs power and water to produce food each day.',
    warning: 'Below 35%: half rations. Stamina and morale drop.',
    critical: 'Below 15%: starvation. Health declines every Sol.',
  },
  {
    key: 'oxygen',
    label: 'Oxygen',
    icon: Wind,
    color: 'text-accent-cyan',
    barColor: 'bg-accent-cyan',
    standard: STANDARD_RESOURCES.oxygen,
    constrained: CONSTRAINED_RESOURCES.oxygen,
    description:
      'Produced by electrolysing water and scrubbing CO2. The life-support system recycles most of it, but leaks and equipment wear consume the surplus.',
    warning: 'Below 35%: thin air. Work capacity and health reduce.',
    critical: 'Below 15%: suffocation risk. Immediate danger to life.',
  },
];

interface StepResourcesProps {
  direction: 'forward' | 'back';
}

export function StepResources({ direction }: StepResourcesProps): ReactElement {
  const [selected, setSelected] = useState<string | null>(null);
  const [condition, setCondition] = useState<'standard' | 'constrained'>('standard');

  return (
    <div className={direction === 'forward' ? 'tut-step-enter' : 'tut-step-enter-back'}>
      <p className="mb-4 text-sm leading-relaxed text-slate-300">
        Four resources keep your outpost running. If any one of them hits zero, the mission is in
        serious trouble. Click each resource to learn what happens when supplies run low.
      </p>

      {/* Condition toggle */}
      <div className="mb-4 flex items-center gap-3">
        <span className="text-xs font-semibold uppercase tracking-wide text-slate-400">
          Starting condition:
        </span>
        <div className="flex rounded-md border border-space-600 bg-space-800/60">
          <button
            type="button"
            onClick={() => setCondition('standard')}
            className={`rounded-l-md px-3 py-1 text-xs font-medium transition-colors ${
              condition === 'standard'
                ? 'bg-mars-red/20 text-mars-orange'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            Standard
          </button>
          <button
            type="button"
            onClick={() => setCondition('constrained')}
            className={`rounded-r-md px-3 py-1 text-xs font-medium transition-colors ${
              condition === 'constrained'
                ? 'bg-mars-red/20 text-mars-orange'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            Resource-constrained
          </button>
        </div>
      </div>

      {/* Resource bars */}
      <div className="space-y-3">
        {RESOURCES.map((res) => {
          const value = condition === 'standard' ? res.standard : res.constrained;
          const isSelected = selected === res.key;
          const Icon = res.icon;

          return (
            <button
              key={res.key}
              type="button"
              onClick={() => setSelected(isSelected ? null : res.key)}
              aria-expanded={isSelected}
              className={`tut-card-interactive w-full rounded-lg border p-3 text-left ${
                isSelected
                  ? 'border-mars-orange/50 bg-mars-red/10'
                  : 'border-space-600 bg-space-700/40'
              }`}
            >
              <div className="flex items-center gap-3">
                <Icon className={`h-5 w-5 shrink-0 ${res.color}`} aria-hidden />
                <div className="flex-1">
                  <div className="flex items-center justify-between">
                    <span className="text-sm font-semibold text-slate-100">{res.label}</span>
                    <span className="font-mono text-sm font-bold text-slate-200">{value}%</span>
                  </div>
                  <div className="mt-1 h-2 w-full overflow-hidden rounded-full bg-space-600">
                    <div
                      className={`tut-bar-fill tut-attr-bar h-full rounded-full ${res.barColor}`}
                      style={{ width: `${value}%` }}
                    />
                  </div>
                </div>
              </div>

              {isSelected ? (
                <div className="mt-3 space-y-2 tut-reveal">
                  <p className="text-xs leading-relaxed text-slate-300">{res.description}</p>
                  <div className="rounded border border-status-warn/30 bg-status-warn/5 px-2 py-1">
                    <p className="text-xs text-status-warn">
                      <span className="font-semibold">Warning:</span> {res.warning}
                    </p>
                  </div>
                  <div className="rounded border border-status-critical/30 bg-status-critical/5 px-2 py-1">
                    <p className="text-xs text-status-critical">
                      <span className="font-semibold">Critical:</span> {res.critical}
                    </p>
                  </div>
                </div>
              ) : null}
            </button>
          );
        })}
      </div>

      {/* Key takeaway */}
      <div className="mt-5 rounded-md border border-accent-blue/30 bg-accent-blue/5 p-3">
        <p className="text-xs leading-relaxed text-slate-300">
          <span className="font-semibold text-accent-blue">Key takeaway:</span> Resources are
          interconnected. Power drives life support which recycles water and oxygen. Food production
          needs both water and power. Losing one resource cascades into the others.
        </p>
      </div>
    </div>
  );
}
